import type { AttendeeInsert } from "@/lib/db/types";
import { DEFAULT_AVAILABILITY, SEED_ROSTER_COMPANY } from "@/lib/seed/constants";

function roster(
  id: string,
  name: string,
  role: string,
  company: string,
  interests: string[],
  goals: string,
  bio?: string,
): AttendeeInsert {
  return {
    id,
    name,
    role,
    company: SEED_ROSTER_COMPANY,
    bio:
      bio ??
      `${name} is a ${role.toLowerCase()} at ${company}, focused on ${interests.slice(0, 2).join(" and ")}.`,
    interests,
    goals,
    availability: DEFAULT_AVAILABILITY,
  };
}

